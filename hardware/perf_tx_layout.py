def panel_gates():
    p = frame("perf_tx_2_gates",
              "ไข่ปลา TX ผัง 2 — สาย GPIO เข้าชิป และการต่อเกตสองชั้นของทั้ง 3 หัวส่ง",
              "ขากลางของชิปต้องเดินสายออกทางข้าง (คอลัมน์ K หรือ P) เสมอ "
              "ห้ามเดินขึ้น/ลงทับตัวชิป")
    p.chip(CHIP_L, CHIP_TOP, CHIP)

    # หัวต่อวางแนวนอนที่ขอบล่าง — ป้ายจะอยู่เหนือหัวต่อในที่ว่าง ไม่ทับสายหรือเลขแถว
    p.header(["G24", "F24", "E24", "D24"], "H1 จาก ESP32", "", side="right")
    p.wire("D24", "A24", C_NEG)
    p.tap("A24", C_NEG)

    # ---- TX1 = เกต 1,2 อยู่คอลัมน์ L ทั้งคู่ ----
    # เดินขึ้นคอลัมน์ E (นอกสุด) แล้วเลี้ยวเข้าขา 1 ที่แถว 36 ซึ่งสูงกว่าปลายสายอื่น
    # จึงไม่ตัดกับเส้นไหนเลย — สายที่เลี้ยวแถวต่ำต้องอยู่คอลัมน์ในกว่าเสมอ
    p.wire("E24", "E36", C_SIG)
    p.wire("E36", "L36", C_SIG)                       # เข้าขา 1 ทางขวาของชิป
    p.wire("L35", "J35", C_SIG)                       # ขา 2 ออกทางขวา
    p.wire("J35", "J34", C_SIG)
    p.wire("J34", "L34", C_SIG)                       # กลับเข้าขา 3
    p.label("J35", "TX1 ขา 2→3", dx=26, dy=-14, colour=C_SIG)

    # ---- TX3 = เกต 3,4 คร่อมสองฝั่ง มีสายอ้อมใต้ชิปหนึ่งเส้น ----
    p.wire("G24", "G32", C_SIG)
    p.wire("G32", "L32", C_SIG)                       # เข้าขา 5
    p.wire("L31", "J31", C_SIG)                       # ขา 6 ออกทางขวา
    p.wire("J31", "J29", C_SIG)
    p.wire("J29", "R29", C_SIG)                       # อ้อมใต้ชิปที่แถว 29
    p.wire("R29", "R31", C_SIG)
    p.wire("R31", "O31", C_SIG)                       # เข้าขา 9 ทางซ้ายของชิป
    p.label("R29", "TX3 ขา 6→9 อ้อมใต้ชิป", dx=44, dy=19, colour=C_SIG)

    # ---- TX2 = เกต 6,5 อยู่คอลัมน์ O ทั้งคู่ ----
    p.wire("F24", "F22", C_SIG)
    p.wire("F22", "S22", C_SIG)                       # อ้อมใต้สุด แถว 22
    p.wire("S22", "S35", C_SIG)
    p.wire("S35", "O35", C_SIG)                       # เข้าขา 13 ทางซ้ายของชิป
    p.wire("O34", "P34", C_SIG)                       # ขา 12 ออกทางซ้าย
    p.wire("P34", "P33", C_SIG)
    p.wire("P33", "O33", C_SIG)                       # กลับเข้าขา 11
    p.label("Q34", "TX2 ขา 12→11", dx=10, dy=-14, colour=C_SIG)
    p.label("Q22", "TX2 อ้อมใต้สุด", dx=0, dy=19, colour=C_SIG)

