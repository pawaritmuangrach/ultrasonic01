from perf_panel import PerfPanel, C_SIG, C_POS, C_NEG, esc  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "diagrams")

COLS = "ABCDEFGHIJKLMNOPQRSTU"
G, P5, G2 = "A", "C", "U"        # บัส GND ขวา · +5V · GND ซ้าย
CHIP_L, CHIP_TOP = "L", 36       # ขา 1 = L36 · ขา 7 = L30 · ขา 8 = O30 · ขา 14 = O36
CHIP = "74HCT04"
NX = 700
ROWS = list(range(44, 19, -1))   # 044 บนสุด ลงไป 020 — ทุกผังใช้ช่วงเดียวกัน


def frame(name, title, sub):
    p = PerfPanel(name, title, sub, ROWS, COLS, width=1340)
    p.bus(G, 44, 20, C_NEG, "GND", side="right")
    p.bus(P5, 44, 20, C_POS, "+5V", side="right")
    p.bus(G2, 44, 20, C_NEG, "GND ซ้าย", side="right")
    return p


def parts_table(p, x, y, rows_):
    h = 30 + 20 * len(rows_)
    p.body.append('<rect x="%d" y="%d" width="336" height="%d" rx="8" fill="#ffffff" '
                  'stroke="#adb5bd" stroke-width="1.6"/>' % (x, y, h))
    p.body.append('<text x="%d" y="%d" font-size="13" font-weight="700" fill="#343a40">'
                  'อุปกรณ์ · เสียบรูไหน</text>' % (x + 12, y + 22))
    for i, (nm, val, a, b) in enumerate(rows_):
        yy = y + 46 + 20 * i
        p.body.append('<text x="%d" y="%d" font-size="12.5" font-weight="700" '
                      'fill="#343a40">%s</text>' % (x + 12, yy, esc(nm)))
        p.body.append('<text x="%d" y="%d" font-size="12.5" fill="#495057">%s</text>'
                      % (x + 118, yy, esc(val)))
        p.body.append('<text x="%d" y="%d" font-size="12.5" font-weight="700" '
                      'fill="#1864ab">%s → %s</text>' % (x + 224, yy, esc(a), esc(b)))


