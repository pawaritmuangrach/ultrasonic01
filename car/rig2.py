"""รูปทรงอาเรย์ชุดใหม่ — RX สี่ตัวที่มุมของ plate_mini + TX ตรงกลาง

เปลี่ยนจากชุดเดิมที่ RX เรียงเป็นเส้นนอนบนบอร์ดทดลอง ซึ่ง**แยกบน-ล่างไม่ได้เลย
ในทางฟิสิกส์** มาเป็นสี่เหลี่ยม จึงได้ทิศแนวตั้งมาด้วย

    Rx1 GPIO35  ซ้ายบน      Rx3 GPIO34  ขวาบน
              TX GPIO18 กลาง
    Rx2 GPIO32  ซ้ายล่าง    Rx4 GPIO33  ขวาล่าง

เบสไลน์ 110 มม. ทั้งสองแกน · ที่ 40 kHz ความยาวคลื่น 8.6 มม.
กำลังแยกแยะ = 8.6/110 = 0.078 เรเดียน = **4.5 องศา ทั้งแนวนอนและแนวตั้ง**

ตัวเลข 4.5 องศานี้คือเพดานจริงของฮาร์ดแวร์ ไม่ว่าจะให้โมเดลทายละเอียดแค่ไหน
ที่ตาราง 80x60 หนึ่งช่องกว้าง 0.73 องศา แปลว่าความเบลอกินราว 6 ช่อง
ตารางที่ละเอียดขึ้นทำให้ภาพเนียนขึ้น ไม่ได้ทำให้เห็นละเอียดขึ้น
"""

# ลำดับช่องมาตรฐาน: ซ้ายบน ขวาบน ซ้ายล่าง ขวาล่าง (อ่านเหมือนอ่านหนังสือ)
# ทุกที่ในโค้ดเรียงตามนี้ ไม่ว่าไฟล์จะบันทึกมาลำดับไหน
PINS = (35, 34, 32, 33)
NAMES = ("TL", "TR", "BL", "BR")
TX_PIN = 18

RX_OFF_MM = 55.0                 # ระยะจากกึ่งกลางแผงถึงศูนย์กลางรู RX ทั้งสองแกน
BASELINE_MM = 2 * RX_OFF_MM      # ระยะระหว่าง RX ฝั่งตรงข้าม
FREQ_HZ = 40_000.0
SOUND_MM_PER_US = 0.343          # 343 m/s ที่ 20 องศาเซลเซียส

# ตำแหน่ง RX บนแผง (x ขวาเป็นบวก, y ขึ้นเป็นบวก, กึ่งกลางแผงเป็นศูนย์)
RX_XY_MM = {"TL": (-RX_OFF_MM, +RX_OFF_MM), "TR": (+RX_OFF_MM, +RX_OFF_MM),
            "BL": (-RX_OFF_MM, -RX_OFF_MM), "BR": (+RX_OFF_MM, -RX_OFF_MM)}

FOV_H_DEG = 58.4
FOV_V_DEG = 45.5


def wavelength_mm():
    return SOUND_MM_PER_US * 1e6 / FREQ_HZ


def resolution_deg():
    """เพดานการแยกแยะเชิงมุมของอาเรย์นี้ — เท่ากันทั้งสองแกนเพราะเบสไลน์เท่ากัน"""
    import math
    return math.degrees(wavelength_mm() / BASELINE_MM)


def max_delay_us():
    """ผลต่างเวลามาถึงสูงสุดระหว่าง RX คู่ที่ไกลที่สุด (ทแยงมุม)

    ใช้เป็นขอบเขตตอนหา TDOA — ค่าที่เกินนี้คือคำนวณผิด ไม่ใช่ของจริง
    """
    import math
    return math.hypot(BASELINE_MM, BASELINE_MM) / SOUND_MM_PER_US


def summary():
    return (f"อาเรย์สี่เหลี่ยม เบสไลน์ {BASELINE_MM:.0f} มม. · "
            f"ความยาวคลื่น {wavelength_mm():.1f} มม. · "
            f"แยกแยะได้ {resolution_deg():.1f} องศา ทั้งสองแกน · "
            f"ผลต่างเวลาสูงสุด {max_delay_us():.0f} ไมโครวินาที")


if __name__ == "__main__":
    print(summary())
    print(f"ช่อง: {' '.join(f'{n}=GPIO{p}' for n, p in zip(NAMES, PINS))}")
    for g, (w, h) in (("40x30", (40, 30)), ("80x60", (80, 60))):
        cw, ch = FOV_H_DEG / w, FOV_V_DEG / h
        print(f"ตาราง {g}: ช่องละ {cw:.2f} x {ch:.2f} องศา · "
              f"ความเบลอ {resolution_deg()/cw:.1f} x {resolution_deg()/ch:.1f} ช่อง")
