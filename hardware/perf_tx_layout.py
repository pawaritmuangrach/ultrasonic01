"""ผังบัดกรี **ภาคส่ง (TX)** ลงแผ่นไข่ปลา — 3 หัวส่งจาก 74HCT04 ตัวเดียว

Run:  python hardware/perf_tx_layout.py   ->  hardware/diagrams/perf_tx_*.svg

แผ่นเดียวกับภาครับ (9x15 cm ยี่ห้อ 顺达) ทุกรูแยกอิสระ ต้องเชื่อมเอง
คอลัมน์ A เริ่มจาก **ขวา** ไล่ไปซ้าย · เลขแถวอยู่ขอบขวา 048 บนสุด ลงไป 001
มองผังกับมองแผ่นจริงเห็นเหมือนกัน ไม่ต้องกลับด้าน

ทำไมทำ 3 TX เลย ไม่ทำ 1 TX ก่อน:
  ข้อมูลชุด walk 5 ช่วง (25 ส.ค. 2026) ชี้ว่าปัญหาใหญ่สุดของภาคส่งตัวเดียวคือ
  **เอคโค่จากคนสะท้อนแบบ specular** — ขยับตัวนิดเดียวความแรงวูบ 40 เท่า
  (วัดได้ 28 mV ถึง 1173 mV ที่ระยะเดียวกัน) ทำให้ 21% ของเฟรมใช้ไม่ได้
  หัวส่งคนละตำแหน่งส่องวัตถุคนละมุม โอกาสที่ทุกตัวหลุดพร้อมกันต่ำกว่ามาก
  และ **TX ถูก RX แพง** — TX เพิ่มตัวใช้แค่ GPIO 1 ขา ไม่กิน ADC ซึ่งเป็นคอขวดจริง

ทำไม 2 เกตต่อหัวส่ง (ไม่ใช่ 1 เกตขับ + 3 เกตขนานแบบเวอร์ชัน A บนบอร์ดทดลอง):
  74HCT04 มี 6 เกต -> 3 หัวส่ง x 2 เกต = ใช้ครบพอดี เหลือชิปสำรองอีก 2 ตัว
  **ที่ 40 kHz การขนานเกตแทบไม่ช่วยเรื่องความแรง** เพราะทรานสดิวเซอร์คือ C 2.4 nF
  ซึ่งมีรีแอกแตนซ์ 1658 โอห์ม ที่ 40 kHz — เทียบกับอิมพีแดนซ์ขาออก 115 โอห์ม (3 เกต)
  หรือ 145 โอห์ม (1 เกต) แล้วต่างกันไม่ถึง 0.3% ของแรงดันที่ตกคร่อมหัวส่ง
  การขนานเกตมีผลกับ "ความชันของขอบ" ซึ่งเราตั้งใจทำให้ช้าลงด้วย R 100 โอห์มอยู่แล้ว
  กระแสพีคต่อเกต = 5V / 145 โอห์ม = 34 mA (พิกัด 25 mA ต่อขา ยิงทีละตัวจึงไม่เกินแพ็กเกจ)

**ต้องเป็น 74HCT04 ไม่ใช่ 74HC04** — HC ต้องการ VIH 3.5V แต่ ESP32 ให้แค่ 3.3V
อาการถ้าใส่ผิดคือ "บางทีก็ยิง บางทีก็ไม่ยิง" ซึ่งไล่บั๊กยากมาก (tx_driver.md §0)

**ห้ามต่อขาออกของชิป (5V) กลับเข้า GPIO ของ ESP32** — พังถาวร ทิศทางมีทางเดียว
ESP32 (3.3V) -> อินพุตชิป เท่านั้น

ทำไมต้องผ่านเกต 2 ชั้น: เพื่อให้ขาออก "ตามขาเข้า" ตอนพัก GPIO เป็น LOW ขาออกก็ LOW
= แรงดันคร่อมหัวส่ง 0V ถ้าใช้เกตชั้นเดียว ตอนพักจะมี 5V คร่อมหัวส่งตลอดเวลา

การแบ่งเกต (74HCT04: เกต n มีขาเข้า/ขาออกติดกัน จึงจับคู่เกตที่อยู่คอลัมน์เดียวกันได้):
  TX1 = เกต 1,2  (ขา 1->2, 3->4)   ทั้งคู่อยู่คอลัมน์ L  ขาออก = ขา 4
  TX2 = เกต 6,5  (ขา 13->12, 11->10) ทั้งคู่อยู่คอลัมน์ O  ขาออก = ขา 10
  TX3 = เกต 3,4  (ขา 5->6, 9->8)   คร่อมสองฝั่ง จึงมีสายข้ามใต้ชิปหนึ่งเส้น ขาออก = ขา 8

บัส 3 เส้น (ลวดแข็ง บัดกรีทุกรูที่ผ่าน):
  A = GND (ขวาสุด) · C = +5V · U = GND ฝั่งซ้าย (เชื่อมกับ A ที่แถว 21)
  GND ฝั่งซ้ายมีไว้ให้ขาที่ 2 ของหัวส่งทั้งสามกลับกราวด์ได้สั้น ๆ
  ไม่ต้องลากข้ามแผ่นไปคอลัมน์ A ซึ่งจะเป็นวงกราวด์ยาวที่กระแส 34 mA วิ่งผ่าน
ชิป DIP-14 วางตั้ง: ขา 1 ที่ L36 ไล่ลงถึงขา 7 ที่ L30 · ขา 8 ที่ O30 ไล่ขึ้นถึงขา 14 ที่ O36
"""
import os
import sys

