def rows():
    b = N.BOARDS["main8"]()
    g = defaultdict(list)
    for ref, val, fp in b["parts"]:
        key = (val, fp) if fp != "TERM2" else ("เทอร์มินอลขันสกรู", fp)
        g[key].append(ref)
    missing = [k for k in g if k not in SPEC and k[1] != "TERM2"]
    if missing:
        raise SystemExit(f"ยังไม่ได้เขียนคำแนะนำของ {missing} ใน SPEC")
    return b, g


def natural(ref):
    """เรียงชื่ออ้างอิงให้ R2B มาก่อน R10B ไม่ใช่เรียงตามตัวอักษรล้วน"""
    import re
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", ref)]


