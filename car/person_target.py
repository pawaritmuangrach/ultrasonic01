"""เฉลยแบบ "เฉพาะสิ่งที่เคลื่อนที่" (คน) — ตัดเฟอร์นิเจอร์และผนังที่นิ่งออกจากภาพเฉลยของกล้อง

ทำไม: ผลรอบห้า ข้ามห้องแล้วโมเดลแทบไม่ดีกว่าการเดาภาพเฉลี่ย สมมติฐานคือเฉลยเดิมมีทั้งคนและ
ของนิ่งของห้อง การทายเฟอร์นิเจอร์ของห้องที่ไม่เคยเห็นจากเสียงล้วนแทบเป็นไปไม่ได้
ถ้าทายเฉพาะคนแล้วข้ามห้องได้ดีขึ้น แปลว่าปัญหาอยู่ที่ของนิ่งในเฉลย

วิธี (ใช้แค่ภาพกล้อง ไม่แตะคลื่นเสียง · ทำแยกทีละช่วงอัด เพราะแต่ละช่วงคือฉากหนึ่ง)
  พื้นหลังของช่อง = ช่องที่มีของ > 50% ของเวลาในช่วงนั้น และระยะของมัน = มัธยฐานของระยะตอนมีของ
  เฉลยคน = ช่องที่มีของ และ (พื้นหลังไม่มีของ หรือ ใกล้กว่าพื้นหลังเกิน MARGIN_CM)
  -> คนที่ยืนหน้าโต๊ะยังเห็น · โต๊ะที่อยู่นิ่งทั้งช่วงหายไป · คนที่ยืนนิ่งเกินครึ่งช่วงจะกลายเป็นพื้นหลัง

ค่าตั้งทั้งหมดกำหนดก่อนดูผลบนห้องสอบ ไม่ได้ปรับให้เข้ากับผล
"""
import numpy as np

MARGIN_CM = 15.0      # ต้องใกล้กว่าพื้นหลังเกินนี้ถึงนับเป็นของที่ย้ายมา (ความเบลอของเสียงในแนวระยะ ~7 ซม.)
BG_FRAC = 0.5         # ช่องที่มีของเกินสัดส่วนนี้ของเวลาในช่วง = พื้นหลัง


def person_dmm(dmm, sec, src):
    """dmm (N, H, W) มม. 0 = ไม่มีของ -> dmm แบบเหลือเฉพาะสิ่งที่เคลื่อนที่ (รูปทรงเดิม)"""
    out = np.zeros_like(dmm)
    for f in np.unique(src):
        for s in np.unique(sec[src == f]):
            if s <= 0:
                continue
            idx = np.nonzero((src == f) & (sec == s))[0]
            d = dmm[idx].astype(np.float32)
            valid = d > 0
            frac = valid.mean(0)
            dm = np.where(valid, d, np.nan)
            with np.errstate(all="ignore"):
                bg = np.nanmedian(dm, axis=0)
            is_bg = frac > BG_FRAC
            fg = valid & (~is_bg[None] | (d < (bg[None] - MARGIN_CM * 10)))
            out[idx] = np.where(fg, dmm[idx], 0)
    return out


def summary(dmm, pdmm, sec, src, fam):
    """ต่อห้อง: ภาพมีของเดิม % · เหลือหลังตัดพื้นหลัง % · เฟรมที่มีคน % · ของนิ่งที่เหลือ %"""
    rows = []
    for f, name in enumerate(fam):
        m = src == f
        o, p = dmm[m] > 0, pdmm[m] > 0
        rows.append((name, 100 * o.mean(), 100 * p.mean(), 100 * (p.sum((1, 2)) >= 10).mean(),
                     100 * (p.mean(0) > 0.9).mean()))
    return rows
