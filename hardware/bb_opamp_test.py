"""ผังเทสออปแอมป์บนบอร์ดทดลอง — วงจรตามแรงดัน (voltage follower) section C

ใช้พิสูจน์ว่าออปแอมป์ตัวหนึ่งพัง/ไม่พัง โดยไม่ต้องพึ่งวงจรบนแผ่นไข่ปลา
MCP6024 ขาเหมือน MCP6004 ทุกประการ (ควอดออปแอมป์ 14 ขา) เทสตัวเดียวกันได้

    python hardware/bb_opamp_test.py
"""
import os
from bb_panel import Panel

OUT = os.path.join(os.path.dirname(__file__), "diagrams")


def build():
    rows = list(range(6, 18))              # ชิปแถว 6-12 · ตัวแบ่งแรงดันแถว 13-17
    p = Panel("bb_opamp_test",
              "เทสออปแอมป์บนบอร์ดทดลอง — วงจรตามแรงดัน (section C: ขา 8,9,10)",
              "ถ้าเอาต์พุต (ขา 8) วิ่งตามอินพุต 1.65V = ชิปดี · ถ้าค้าง 0 หรือ 3.3 = พัง",
              rows, rail="left", chip_row0=6, chip_name="MCP6024", width=880)
    p.chip()

    # ---- ไฟเลี้ยงชิป ----
    p.to_rail("9E", "+", below=False)      # ขา 4 (VDD) -> ราง +
    p.to_rail("9F", "-", below=True)       # ขา 11 (VSS) -> ราง -

    # ---- ตัวแบ่งแรงดัน 10k/10k สร้าง 1.65V (ครึ่งขวาของบอร์ด) ----
    p.part("13G", "15G", "10k", "R")       # R1
    p.part("15G", "17G", "10k", "R")       # R2
    p.to_rail("13G", "+", below=False)     # หัวบน R1 -> ราง +
    p.to_rail("17G", "-", below=True)      # หัวล่าง R2 -> ราง -

    # ---- จุดกลาง (แถว 15) -> ขา 10 (อินพุต+) เดินสายริมขวาสุด คอลัมน์ J ----
    p.vlane("15G", "10J", 452)             # ออกจากจุดต่อ R1/R2 -> ขา 10 (โหนดขา 10)

    # ---- ป้อนกลับ ขา 8 -> ขา 9 (คอลัมน์ H ชิดชิป) ----
    p.wire("12H", "11H")                   # H12=ขา8 · H11=ขา9

    # ---- จุดวัด ----
    p.tag("12J", "วัดที่นี่", dx=14, dy=4, anchor="start", colour="#e03131")
    p.dot("12J", "#e03131")

    NX = 524
    p.note(NX, 96, [
        "ต่อ 6 จุด (ดูหมายเลขขาบนชิป)",
        "1. ขา 4 (VDD)  ->  ราง +  (สายแดง)",
        "2. ขา 11 (VSS) ->  ราง -  (สายดำ)",
        "3. R1 10k : ราง +  ->  จุดกลาง",
        "4. R2 10k : จุดกลาง  ->  ราง -",
        "5. จุดกลาง  ->  ขา 10 (อินพุต +)",
        "6. ขา 8 (เอาต์)  ->  ขา 9 (ป้อนกลับ)",
    ], colour="#1971c2", bg="#e7f5ff", w=330)

    p.note(NX, 256, [
        "วัดผล : สายดำที่ราง -  วัดที่ขา 8",
        "~1.65V  = ชิปดี (เอาต์ตามอินพุต)",
        "ค้าง 0 หรือ 3.3 / ไม่ตาม = ชิปพัง",
        "R1 R2 ต้องเป็น 10k เท่ากันทั้งคู่",
    ], colour="#2f9e44", bg="#ebfbee", w=330)

    p.note(NX, 356, [
        "เทสเร็ว (ไม่ต้องใช้ R เลย)",
        "เอาขา 10 แตะราง + -> ขา 8 ควร ~3.3",
        "เอาขา 10 แตะราง - -> ขา 8 ควร ~0",
        "เอาต์วิ่งตามที่แตะ = ชิปดี",
    ], colour="#f08c00", bg="#fff4e6", w=330)

    p.note(NX, 456, [
        "ข่าวดี",
        "MCP6024 ขาเหมือน MCP6004 เป๊ะ",
        "และเร็วกว่า (10MHz เทียบ 1MHz)",
        "ถ้าตัวนี้ผ่านเทส เอาเข้าผัง 2 ได้เลย",
        "ไม่ต้องหา MCP6004 มาแทน",
    ], colour="#ae3ec9", bg="#f8f0fc", w=330)
    return p


if __name__ == "__main__":
    p = build()
    print("เขียน", p.write(OUT))
