def _put(p, ref, x, y, mir):
    """วางชิ้นเดียว พลิกกระจกให้ถ้าเป็นบล็อกฝั่งขวา"""
    p[ref] = (MIRROR_X - x, y, 180) if mir else (x, y, 0)


def _rx_block(p, chip, ia, ib, ox, oy, mir):
    """หนึ่งบล็อก = ชิป 1 ตัว + ช่องรับ 2 ช่อง

    **การหมุน 180 องศาพลิกทั้งแกน x และ y** แถวขาของชิปจึงสลับบนล่างไปด้วย
    ในบล็อกปกติ section A+B (ขา 1-7) อยู่แถวล่าง ใกล้ช่องล่าง
    ในบล็อกที่พลิก ขา 1-7 ไปอยู่แถวบน จึงต้องสลับให้ช่องที่ใช้ A+B ขึ้นไปอยู่บนด้วย
    ไม่งั้นลายต้องอ้อมข้ามตัวชิป ซึ่งเป็นสาเหตุที่ฝั่งขวาเดินไม่ผ่าน 55 จุด
    """
    # ช่อง ia ใช้ section A+B · ช่อง ib ใช้ section C+D (ตามที่ netlist กำหนด)
    # บล็อกปกติ: ขา 1-7 (A,B) อยู่แถวล่าง -> ia ไปอยู่ตำแหน่งล่าง
    # บล็อกที่พลิก: ขา 1-7 ไปอยู่แถวบน   -> ia ต้องขึ้นไปอยู่ตำแหน่งบนด้วย
    pos_a, pos_b = (_BLK_B, _BLK_A) if mir else (_BLK_A, _BLK_B)
    for tag, dx, dy in pos_a:
        _put(p, _SUF[tag].format(i=ia), ox + dx, oy + dy, mir)
    for tag, dx, dy in pos_b:
        _put(p, _SUF[tag].format(i=ib), ox + dx, oy + dy, mir)
    # เลื่อนจุดยึดชิปขึ้น 7.62 เมื่อพลิก เพื่อให้สองแถวขาตกที่ y เดิม
    _put(p, f"U{chip}", ox + 40, oy + 34 + (7.62 if mir else 0), mir)
    _put(p, f"CD{chip}", ox + 40, oy + (48.6 if mir else 27), mir)


