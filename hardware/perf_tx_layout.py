    parts_table(p, NX, 230, [
        ("H1 จาก ESP32", "ตัวผู้ 4 ขา", "G24", "D24"),
        ("  ขาซ้ายสุด G24", "= TX3 เข้า", "G24", "L32"),
        ("  ขา F24", "= TX2 เข้า", "F24", "O35"),
        ("  ขา E24", "= TX1 เข้า", "E24", "L36"),
        ("  ขาขวาสุด D24", "= GND", "D24", "A24"),
        ("TX1 ขา 2→3", "สาย 3 ท่อน", "L35", "L34"),
        ("TX2 ขา 12→11", "สาย 3 ท่อน", "O34", "O33"),
        ("TX3 ขา 6→9", "สาย 5 ท่อน", "L31", "O31"),
    ])
    p.note(NX, 428, [
        "ขาชิปที่ใช้ ทั้ง 14 ขา",
        "1 = TX1 เข้า      14 = +5V",
        "2 → 3 (ต่อกัน)    13 = TX2 เข้า",
        "4 = TX1 ออก      12 → 11 (ต่อกัน)",
        "5 = TX3 เข้า      10 = TX2 ออก",
        "6 → 9 (ต่อกัน)     9 = ต่อจากขา 6",
        "7 = GND           8 = TX3 ออก",
    ], colour="#1971c2", bg="#e7f5ff", w=336)
    p.note(NX, 592, [
        "ทำไมสายต้องออกทางข้างของชิป",
        "ส.ค. 2026 ผัง VREF ของภาครับเดินสาย",
        "ดิ่งลงหาขา 10 ทะลุตัวชิป จุดต่อเลยถูก",
        "ตัวชิปบัง ผู้ต่อมองไม่เห็นจึงบัดกรีไป",
        "ลงขา 14 แทน = อินพุตลอย เอาต์พุตชน",
        "ขอบล่าง ไล่บั๊กเสียเวลาหลายรอบ",
        "ผังนี้ทุกสายจึงโผล่ออกข้างให้เห็นชัด",
    ], colour="#f08c00", bg="#fff4e6", w=336)
    return p


