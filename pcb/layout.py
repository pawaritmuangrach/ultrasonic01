# ตำแหน่งภายในบล็อก (อ้างมุมซ้ายล่างของบล็อก) — ยกมาจาก rx2 ทั้งชุด
# ช่อง a อยู่ใต้ชิป ใช้ section A+B · ช่อง b อยู่เหนือชิป ใช้ section C+D
