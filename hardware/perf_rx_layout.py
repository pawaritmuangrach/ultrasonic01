def panel_input(name="perf_3_input_stage1", ch=1, no=3, chip="MCP6004 ตัวที่ 1",
                split_in=False):
    """split_in=True : แยกขา Cin ออกจากรูของเทอร์มินอล

    ช่อง 1 (บัดกรีไปแล้ว) ใช้ split_in=False เพื่อให้ผังตรงกับแผ่นจริง — ที่นั่นขา Cin
    กับขาสกรู KF301 ลงรู F44 รูเดียวกัน ซึ่งประกอบได้เพราะพันขารวมกันก่อนเสียบ
    แต่เป็นวิธีที่เปราะ: ถอดเทอร์มินอลทีต้องรื้อ Cin ด้วย และรูเดียวรับสองขาทำให้
    รอยบัดกรีนูนจนตัวเทอร์มินอลวางไม่สนิท
    ช่องใหม่ตั้งแต่ช่อง 2 เป็นต้นไปใช้ split_in=True : เทอร์มินอลอยู่ F44 ตามเดิม
    แล้วโดดสายไปเข้า Cin ที่คอลัมน์ H ซึ่งพ้นตัวเทอร์มินอล (F44 ห่าง H44 สองรู)
    """
    rows = rows_down(44, 29)
    p = frame(name,
              f"ไข่ปลา ผัง {no} — ช่อง {ch}: อินพุตและสเตจขยายที่ 1",
              "หัวรับ → Cin → โหนด IN → ขา 3 · Rf1 กลับขา 2 · Rg1-Cg1 ลง GND",
              rows)
    p.chip(CHIP_L, CHIP_TOP, chip)

    # หัวรับต่อผ่านเทอร์มินอล KF301 (ขันสกรู) — บัดกรีสาย 25AWG แข็งที่ขาหัวรับแล้วขันเข้า
    # จับแน่น ถอดเปลี่ยนหัวง่าย และสัมผัสดีกว่า pin header ที่จุดอินพุตซึ่งไวต่อ noise ที่สุด
    # KF301 ระยะขา 5.08mm = 2 รู (F44 สัญญาณ · D44 GND · เว้น E44 ตรงกลาง)
    p.terminal(["F44", "D44"], f"H1 หัวรับช่อง {ch}", "")
    p.wire("D44", "A44", C_NEG, lane=p.y[43], side="v")
    p.tap("A44", C_NEG)

    if split_in:
        # ขาสกรูกับขา Cin ต้องอยู่คนละรู — โดดสายข้าม G44 ไปเข้า Cin ที่คอลัมน์ H
        p.wire("F44", "H44", C_SIG)
        p.part("H44", "H42", "Cin", "C")
        p.solder("H42", "H41", C_SIG)                    # โหนด IN
        p.part("H41", "K41", "Rb", "R")
        p.wire("K41", "U41", C_VREF)                     # ไปบัส VREF
    else:
        # ช่อง 1 บัดกรีไปแล้วแบบนี้ (พันขา Cin กับขาสกรูเข้าด้วยกันก่อนเสียบ)
        # ผังต้องตรงกับแผ่นจริงเสมอ จึงไม่แก้ย้อนหลัง แค่ยกเว้นให้ตัวตรวจ
        p.allow_shared["F44"] = "ช่อง 1 บัดกรีแบบรูรวมไปแล้ว ผังต้องตรงกับแผ่นจริง"
        p.part("F44", "F42", "Cin", "C")
        p.solder("F42", "F41", C_SIG)                    # โหนด IN
        p.part("F41", "I41", "Rb", "R")
        p.wire("I41", "U41", C_VREF)                     # ไปบัส VREF
    p.tap("U41", C_VREF)
    # โหนด IN -> ขา 3 (+INA) ผ่านคอลัมน์ H ซึ่ง "ว่างทั้งแผ่น" ทั้ง 4 ผัง
    # ห้ามเดินลงคอลัมน์ F เด็ดขาด: F38/F37/F34 คือโหนด VREF กับขา GND ของ Rv2 (ผัง 2)
    # ซึ่งในผังนี้ไม่ได้วาดไว้ คอลัมน์ F จึงดู "ว่าง" ทั้งที่มีขาอุปกรณ์เสียบอยู่จริง
    if split_in:
        # โหนด IN อยู่คอลัมน์ H อยู่แล้ว ลงตรงไปเข้าขา 3 ได้เลย ไม่ต้องออกข้างก่อน
        p.wire("H41", "L34", C_SIG, lane=p.x["H"], side="h")
    else:
        p.wire("F42", "H42", C_SIG)                      # ออกข้างไปคอลัมน์ว่างก่อน
        p.wire("H42", "L34", C_SIG, lane=p.x["H"], side="h")  # ลงคอลัมน์ H -> เข้าขา 3
    _x3, _y3 = p.p("L34")
    p.top.append(f'<circle cx="{_x3}" cy="{_y3}" r="6" fill="{C_SIG}"/>')
    p.label("L34", "ขา 3 (อินพุต+)", dx=20, dy=-11, colour=C_SIG, anchor="start")

    p.wire("L36", "J36", C_SIG)
    p.solder("J36", "I36", C_SIG)                        # โหนดขาออกสเตจ 1
    p.part("I36", "G36", "Rf1", "R")
    p.solder("G36", "G35", C_SIG)                        # โหนด −INA
